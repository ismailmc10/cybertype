-- CyberType results review. Apply ONCE after 001, as project owner.
-- No table/data drops. Existing machine scores and in-progress runs are preserved.
-- The transaction locks out old RPC executions before changing their contract.
begin;
lock table public.cyber_event in access exclusive mode;

alter table public.cyber_event
 add column if not exists leaderboard_visible boolean not null default false,
 add column if not exists results_finalized boolean not null default false,
 add column if not exists results_version bigint not null default 0;
do $$ begin
 if not exists(select 1 from pg_constraint where conrelid='public.cyber_event'::regclass and conname='cyber_review_state') then
  alter table public.cyber_event add constraint cyber_review_state check
   ((not results_finalized or status='ended') and
    (not leaderboard_visible or (results_finalized and status='ended')));
 end if;
end $$;

create table if not exists public.cyber_score_adjustments (
 id bigint generated always as identity primary key,
 event_id int not null default 1 references public.cyber_event(id),
 user_id uuid not null references public.cyber_runs(id) on delete cascade,
 delta integer not null check(delta<>0 and delta between -100000 and 100000),
 reason text not null check(length(btrim(reason)) between 5 and 1000),
 category text not null check(category in ('malpractice','rule_violation','grace','sportsmanship','technical_compensation','manual_correction','other')),
 created_by uuid not null references auth.users(id),
 created_at timestamptz not null default clock_timestamp(),
 request_id uuid not null unique
);
create index if not exists cyber_adjustments_participant on public.cyber_score_adjustments(event_id,user_id);
alter table public.cyber_score_adjustments enable row level security;
revoke all on public.cyber_score_adjustments from public,anon,authenticated;
grant select on public.cyber_score_adjustments to authenticated;
drop policy if exists adjustments_admin_read on public.cyber_score_adjustments;
create policy adjustments_admin_read on public.cyber_score_adjustments for select to authenticated using(public.cyber_is_admin());

-- Keep score as the original, machine-generated value for compatibility.
-- Final score is generated by Postgres; the summed adjustment cache is maintained
-- only by the private trigger. No caller-supplied final/base scores are accepted.
alter table public.cyber_board
 add column if not exists base_score integer generated always as (score) stored,
 add column if not exists manual_adjustment bigint not null default 0,
 add column if not exists final_score bigint generated always as (score::bigint + manual_adjustment) stored;

create or replace function public.cyber_adjustment_total() returns trigger
language plpgsql security definer set search_path='' as $$
declare target uuid;
begin
 if TG_OP='UPDATE' then raise exception 'Adjustments are append-only. Add a compensating adjustment with a reason.';end if;
 target:=case when TG_OP='DELETE' then OLD.user_id else NEW.user_id end;
 update public.cyber_board set manual_adjustment=(select coalesce(sum(a.delta),0) from public.cyber_score_adjustments a where a.user_id=target and a.event_id=1) where id=target;
 return null;
end $$;
revoke all on function public.cyber_adjustment_total() from public,anon,authenticated;
drop trigger if exists cyber_adjustment_rollup on public.cyber_score_adjustments;
create trigger cyber_adjustment_rollup after insert or update or delete on public.cyber_score_adjustments for each row execute function public.cyber_adjustment_total();
update public.cyber_board b set manual_adjustment=(select coalesce(sum(a.delta),0) from public.cyber_score_adjustments a where a.user_id=b.id and a.event_id=1);

-- Applies to direct REST, SQL, canonical standings, and Realtime row delivery.
drop policy if exists board_read on public.cyber_board;
create policy board_read on public.cyber_board for select to anon,authenticated using(
 public.cyber_is_admin() or exists(select 1 from public.cyber_event e where e.id=1 and e.leaderboard_visible and e.results_finalized and e.status='ended')
);
-- Canonical ordering: final score descending, UUID ascending (existing tie rule).
-- SECURITY INVOKER deliberately preserves RLS for direct callers.
create or replace function public.cyber_standings() returns table(
 id uuid, alias text, score int, round int, status text, wpm numeric,
 accuracy numeric, base_score int, manual_adjustment bigint, final_score bigint, rank bigint
) language sql stable security invoker set search_path='' as $$
 select b.id,b.alias,b.score,b.round,b.status,b.wpm,b.accuracy,b.base_score,b.manual_adjustment,b.final_score,
 row_number() over(order by b.final_score desc,b.id)
 from public.cyber_board b order by b.final_score desc,b.id
$$;
revoke all on function public.cyber_standings() from public;
grant execute on function public.cyber_standings() to anon,authenticated;

create or replace function public.cyber_publish(uid uuid,r jsonb) returns void language plpgsql security definer set search_path='' as $$
declare c jsonb:=r->'cards'->-1;total int;
begin
 select coalesce(sum((x->>'score')::int),0) into total from jsonb_array_elements(r->'cards') x;
 insert into public.cyber_board(id,alias,score,round,status,wpm,accuracy) values(uid,r->>'alias',total,(r->>'round')::int,case when coalesce((r->>'blocked')::boolean,false) then 'blocked' else r->>'status' end,coalesce((c->>'wpm')::numeric,0),coalesce((c->>'accuracy')::numeric,100))
 on conflict(id) do update set score=excluded.score,round=excluded.round,status=excluded.status,wpm=excluded.wpm,accuracy=excluded.accuracy,alias=excluded.alias;
end$$;
revoke all on function public.cyber_publish(uuid,jsonb) from public;

create or replace function public.cyber_api(action text,payload jsonb default '{}') returns jsonb language plpgsql security definer set search_path='' as $$
declare e public.cyber_event%rowtype;uid uuid:=auth.uid();adm boolean:=public.cyber_is_admin();t double precision;r jsonb;rec record;cmd text;cfg jsonb;k text;v numeric;boards jsonb:='[]';standings jsonb:='[]';participants jsonb;logs jsonb;adjustments jsonb;personal jsonb;target uuid;amount integer;why text;kind text;request uuid;previous bigint;effective bigint;prior public.cyber_score_adjustments%rowtype;
begin
 select * into e from public.cyber_event where id=1 for update;
 t:=e.clock+case when e.status='running' then extract(epoch from clock_timestamp()-e.active_since) else 0 end;
 if action not in ('snapshot','join','tick','admin') then raise exception 'Invalid action';end if;
 if action<>'snapshot' and uid is null then raise exception 'Authentication required';end if;
 -- Settle running timers even when a participant disconnects. Calls are serialized.
 if e.status='running' then
  for rec in select * from public.cyber_runs where state->>'status' not in ('complete','ended') loop
   r:=public.cyber_advance(rec.state,e.settings,t);
   if r<>rec.state then update public.cyber_runs set state=r where id=rec.id;perform public.cyber_publish(rec.id,r);end if;
  end loop;
 end if;
 if action='join' then
  if not e.registration or e.status='ended' then raise exception 'Registration is closed';end if;
  if coalesce(length(trim(payload->>'alias')),0) not between 2 and 30 then raise exception 'Choose a public alias of 2–30 characters';end if;
  r:=jsonb_build_object('id',uid,'alias',trim(payload->>'alias'),'round',1,'cards','[]'::jsonb,'status','ready','ready',t+4,'last_seen',now(),'blocked',false);
  insert into public.cyber_runs values(uid,r) on conflict(id) do nothing;
  select state into r from public.cyber_runs where id=uid;perform public.cyber_publish(uid,r);
 elsif action='tick' then
  select state into r from public.cyber_runs where id=uid;
  if r is null then raise exception 'Join the event first';end if;
  if jsonb_typeof(coalesce(payload->'chars','[]'))<>'array' or jsonb_array_length(coalesce(payload->'chars','[]'))>50 then raise exception 'Invalid input batch';end if;
  if e.status='running' and (payload->>'round')::int=(r->>'round')::int then r:=public.cyber_advance(r,e.settings,t,coalesce(payload->'chars','[]'),coalesce((payload->>'seq')::int,0));end if;
  r:=r||jsonb_build_object('last_seen',now());update public.cyber_runs set state=r where id=uid;perform public.cyber_publish(uid,r);
 elsif action='admin' then
  if not adm then raise exception 'Admin access required';end if;
  cmd:=payload->>'command';
  if cmd in ('end','reset') and (payload->>'confirm') is distinct from 'CONFIRM' then raise exception 'Confirmation required';end if;
  -- Explicit server-side admin and confirmation checks also protect direct RPC.
  if cmd in ('adjust','finalize','reopen','reveal','hide') then
   if payload->>'confirm' is distinct from 'CONFIRM' then raise exception 'Confirmation required';end if;
   if cmd='adjust' then
    request:=(payload->>'request_id')::uuid;
    if request is null then raise exception 'Adjustment request ID required';end if;
    select * into prior from public.cyber_score_adjustments where request_id=request;
    if found then
     if prior.created_by<>uid or prior.user_id is distinct from (payload->>'id')::uuid or prior.delta is distinct from (payload->>'delta')::integer or prior.reason is distinct from btrim(payload->>'reason') or prior.category is distinct from payload->>'category' then raise exception 'Request ID already used for different adjustment';end if;
     -- A lost-response retry is acknowledged, including after finalization.
     cmd:='adjust_retry';
    end if;
   end if;
   if cmd<>'adjust_retry' and (payload->>'results_version')::bigint is distinct from e.results_version then
    raise exception 'Results changed since your review. Refresh and review the latest standings before confirming.';
   end if;
  end if;
  if cmd='adjust_retry' then null;
  elsif cmd='adjust' then
   if e.status<>'ended' then raise exception 'End the event before applying score adjustments';end if;
   if e.results_finalized then raise exception 'Results are finalized. Reopen results before adjusting scores.';end if;
   target:=(payload->>'id')::uuid;why:=btrim(payload->>'reason');kind:=payload->>'category';
   if coalesce(payload->>'delta','') !~ '^-?[0-9]+$' then raise exception 'Adjustment must be a signed whole number';end if;
   amount:=(payload->>'delta')::integer;
   if amount=0 or amount not between -100000 and 100000 then raise exception 'Adjustment must be nonzero and between -100000 and +100000';end if;
   if why is null or length(why) not between 5 and 1000 then raise exception 'A reason of 5–1000 characters is required';end if;
   if kind is null or kind not in ('malpractice','rule_violation','grace','sportsmanship','technical_compensation','manual_correction','other') then raise exception 'Choose an adjustment category';end if;
   select final_score into previous from public.cyber_board where id=target;
   if not found then raise exception 'Participant not found';end if;
   insert into public.cyber_score_adjustments(event_id,user_id,delta,reason,category,created_by,request_id) values(1,target,amount,why,kind,uid,request);
   select final_score into effective from public.cyber_board where id=target;
   update public.cyber_event set results_version=results_version+1 where id=1;
   payload:=jsonb_build_object('participant',target,'alias',(select alias from public.cyber_board where id=target),'delta',amount,'reason',why,'category',kind,'created_by',uid,'request_id',request,'previous_final_score',previous,'final_score',effective);
  elsif cmd='finalize' then
   if e.status<>'ended' then raise exception 'End the event before finalizing results';end if;
   if e.results_finalized then raise exception 'Results are already finalized';end if;
   update public.cyber_event set results_finalized=true,leaderboard_visible=false,results_version=results_version+1 where id=1;
  elsif cmd='reopen' then
   if not e.results_finalized then raise exception 'Results are not finalized';end if;
   update public.cyber_event set results_finalized=false,leaderboard_visible=false,results_version=results_version+1 where id=1;
  elsif cmd='reveal' then
   if e.status<>'ended' or not e.results_finalized then raise exception 'End the event and finalize results before revealing';end if;
   update public.cyber_event set leaderboard_visible=true,results_version=results_version+1 where id=1;
  elsif cmd='hide' then
   update public.cyber_event set leaderboard_visible=false,results_version=results_version+1 where id=1;
  elsif cmd='registration' then update public.cyber_event set registration=(payload->>'open')::boolean where id=1;
  elsif cmd='start' then
   if e.status not in ('waiting','paused') then raise exception 'Event cannot be started';end if;
   update public.cyber_event set status='running',active_since=clock_timestamp() where id=1;
  elsif cmd='pause' then
   if e.status<>'running' then raise exception 'Event is not running';end if;
   update public.cyber_event set status='paused',clock=t,active_since=null where id=1;
  elsif cmd='end' then
   if e.status='ended' then raise exception 'Event is already ended';end if;
   update public.cyber_event set status='ended',clock=t,active_since=null,registration=false,leaderboard_visible=false,results_finalized=false,results_version=results_version+1 where id=1;
   for rec in select * from public.cyber_runs where state->>'status'<>'complete' loop
    r:=rec.state||'{"status":"ended"}';
    if r->>'status'='ended' and jsonb_array_length(r->'cards')>0 then
     r:=jsonb_set(r,array['cards',(jsonb_array_length(r->'cards')-1)::text,'status'],to_jsonb(case when rec.state->>'status'='active' then 'ended' else rec.state->'cards'->-1->>'status' end));
    end if;
    update public.cyber_runs set state=r where id=rec.id;perform public.cyber_publish(rec.id,r);
   end loop;
  elsif cmd='reset' then
   payload:=payload||jsonb_build_object('cleared_runs',(select count(*) from public.cyber_runs),'cleared_adjustments',(select count(*) from public.cyber_score_adjustments));
   delete from public.cyber_runs;delete from public.cyber_board;update public.cyber_event set status='waiting',clock=0,active_since=null,registration=true,leaderboard_visible=false,results_finalized=false,results_version=results_version+1 where id=1;
  elsif cmd='block' then
   if e.results_finalized then raise exception 'Reopen results before changing participant status';end if;
   update public.cyber_event set results_version=results_version+1 where id=1;
   update public.cyber_runs set state=state||jsonb_build_object('blocked',(payload->>'blocked')::boolean) where id=(payload->>'id')::uuid returning state into r;
   if r is null then raise exception 'Participant not found';end if;perform public.cyber_publish((payload->>'id')::uuid,r);
  elsif cmd='configure' then
   if e.status<>'waiting' or exists(select 1 from public.cyber_runs where jsonb_array_length(state->'cards')>0) then raise exception 'Settings lock after the event starts. Reset to reconfigure.';end if;
   cfg:=payload->'settings';
   if cfg is null or jsonb_typeof(cfg)<>'object' then raise exception 'Settings required';end if;
   foreach k in array array['durations','prompts','multipliers','penalties'] loop if jsonb_typeof(cfg->k) is distinct from 'array' then raise exception 'Missing array: %',k;end if;end loop;
   foreach k in array array['date','time','venue','department','type'] loop if coalesce(length(trim(cfg->>k)),0) not between 1 and 100 then raise exception 'Invalid event detail: %',k;end if;end loop;
   foreach k in array array['fee','first','second','points','speedWeight'] loop v:=(cfg->>k)::numeric;if v is null or v<0 or v>100000 then raise exception 'Invalid setting: %',k;end if;end loop;
   if jsonb_array_length(cfg->'durations')<>3 or jsonb_array_length(cfg->'prompts')<>3 or jsonb_array_length(cfg->'multipliers')<>5 or jsonb_array_length(cfg->'penalties')<>2 then raise exception 'Invalid round configuration';end if;
   for rec in select value from jsonb_array_elements_text(cfg->'durations') loop if rec.value is null or rec.value::numeric not between 5 and 600 then raise exception 'Durations must be 5–600 seconds';end if;end loop;
   for rec in select value from jsonb_array_elements_text(cfg->'prompts') loop if rec.value is null or length(rec.value) not between 10 and 2000 or rec.value ~ '[^ -~]' then raise exception 'Prompts must be 10–2000 printable ASCII characters';end if;end loop;
   if cfg->'prompts'->>2 !~ '^[a-fA-F0-9]+$' then raise exception 'Hash prompt must be hexadecimal';end if;
   for rec in select value from jsonb_array_elements_text(cfg->'multipliers') loop if rec.value is null or rec.value::numeric not between 1 and 10 then raise exception 'Multipliers must be 1–10';end if;end loop;
   if cfg->'penalties'->>0 is null or cfg->'penalties'->>1 is null or (cfg->'penalties'->>0)::numeric<0 or (cfg->'penalties'->>1)::numeric<=(cfg->'penalties'->>0)::numeric or (cfg->'penalties'->>1)::numeric>100000 then raise exception 'Second penalty must exceed first';end if;
   if (cfg->'multipliers'->>0)::numeric<>1 or (cfg->'multipliers'->>1)::numeric<=(cfg->'multipliers'->>0)::numeric or (cfg->'multipliers'->>2)::numeric<=(cfg->'multipliers'->>1)::numeric or (cfg->'multipliers'->>3)::numeric<=(cfg->'multipliers'->>2)::numeric or (cfg->'multipliers'->>4)::numeric<=(cfg->'multipliers'->>3)::numeric then raise exception 'Multipliers must start at 1 and increase at each milestone';end if;
   update public.cyber_event set settings=cfg where id=1;
  else raise exception 'Unknown admin command';end if;
  if cmd<>'adjust_retry' then insert into public.cyber_audit(actor,action,details) values(uid,cmd,payload);end if;
 end if;
 select * into e from public.cyber_event where id=1;
 select state into r from public.cyber_runs where id=uid;
 -- Never collect/return private standings to a non-admin while locked.
 if e.leaderboard_visible and e.results_finalized and e.status='ended' then
  select coalesce(jsonb_agg(to_jsonb(b) order by b.rank),'[]') into boards from public.cyber_standings() b;
 end if;
 -- Personal summary deliberately has no rank or comparison information.
 select jsonb_build_object('base_score',b.base_score,'manual_adjustment',b.manual_adjustment,'final_score',b.final_score) into personal from public.cyber_board b where b.id=uid;
 if adm then
  select coalesce(jsonb_agg(to_jsonb(b) order by b.rank),'[]') into standings from public.cyber_standings() b;
  select coalesce(jsonb_agg(state),'[]') into participants from public.cyber_runs;
  select coalesce(jsonb_agg(to_jsonb(a) order by a.created_at desc,a.id desc),'[]') into adjustments from public.cyber_score_adjustments a;
  select coalesce(jsonb_agg(to_jsonb(a) order by a.id desc),'[]') into logs from(select log.id,log.actor,log.action,log.details,log.created_at from public.cyber_audit log order by log.id desc limit 100)a;
 end if;
 return jsonb_build_object('event',jsonb_build_object('status',e.status,'registration',e.registration,'clock',e.clock+case when e.status='running' then extract(epoch from clock_timestamp()-e.active_since) else 0 end,'settings',e.settings,'leaderboard_visible',e.leaderboard_visible,'results_finalized',e.results_finalized,'results_version',e.results_version),'run',r,'personal_score',personal,'leaderboard',boards,'standings',standings,'admin',adm,'participants',participants,'adjustments',adjustments,'audit',logs);
end$$;
revoke all on function public.cyber_api(text,jsonb) from public;
grant execute on function public.cyber_api(text,jsonb) to anon,authenticated;

-- Keep the existing Realtime subscriptions. Updates to the canonical board and
-- public event flags invalidate snapshots. Adjustment reasons never travel on
-- a public Realtime table, and locked board rows are filtered by RLS.
notify pgrst, 'reload schema';
commit;
